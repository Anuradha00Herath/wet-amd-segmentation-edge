"""
report_generator.py
-------------------
Generates benchmark summary reports in multiple formats:
  - Markdown (.md)
  - CSV (.csv)
  - Console table

Designed to be called after running the full benchmark pipeline so
all results are written to results/ in one shot.

Reuses CSVLogger from utils/logger.py — no duplicate CSV logic here.
"""

import os
from datetime import datetime
from typing import Any, Dict, List, Optional

from utils.logger import CSVLogger, get_logger
from models.baseline_model import CLASS_NAMES

_log = get_logger(__name__)


# --------------------------------------------------------------------------- #
#  Markdown report                                                             #
# --------------------------------------------------------------------------- #

def generate_markdown_report(
    accuracy_metrics:  Dict[str, float],
    profiling_metrics: Dict[str, Any],
    energy_metrics:    Dict[str, Any],
    cfg,
    label: str = "baseline_fp32",
    filename: str = "benchmark_report.md",
) -> str:
    """
    Generate a full markdown benchmark report and save to results/.

    Args:
        accuracy_metrics:  Output of MetricAccumulator.mean().
        profiling_metrics: Output of ModelProfiler.run().
        energy_metrics:    Output of EnergyMonitor.track().
        cfg:               Project Config.
        label:             Experiment label.
        filename:          Output filename.

    Returns:
        Path to the saved markdown file.
    """
    ts   = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    path = os.path.join(cfg.results_dir, filename)
    os.makedirs(cfg.results_dir, exist_ok=True)

    lines = [
        f"# Benchmark Report — {label}",
        f"**Generated:** {ts}  ",
        f"**Device:** {profiling_metrics.get('device', 'N/A')}  ",
        "",
        "---",
        "",
        "## 1. Segmentation Accuracy",
        "",
        "| Metric | Value |",
        "|--------|-------|",
        f"| Mean Dice  | {accuracy_metrics.get('mean_dice', 0):.4f} |",
        f"| Mean IoU   | {accuracy_metrics.get('mean_iou',  0):.4f} |",
        f"| Pixel Acc  | {accuracy_metrics.get('pixel_acc', 0):.4f} |",
        "",
        "### Per-Class Dice",
        "",
        "| Class | Dice |",
        "|-------|------|",
    ]

    for name in CLASS_NAMES:
        key   = f"dice_{name.lower().replace(' ', '_')}"
        score = accuracy_metrics.get(key, 0.0)
        lines.append(f"| {name} | {score:.4f} |")

    lines += [
        "",
        "---",
        "",
        "## 2. Model Complexity",
        "",
        "| Metric | Value |",
        "|--------|-------|",
        f"| Parameters      | {profiling_metrics.get('n_params', 0):,} |",
        f"| Model Size (MB) | {profiling_metrics.get('model_size_mb', 0):.2f} |",
        f"| FLOPs           | {profiling_metrics.get('flops') or 'N/A'} |",
        f"| Peak RAM (MB)   | {profiling_metrics.get('peak_ram_mb', 0):.2f} |",
        f"| Peak GPU (MB)   | {profiling_metrics.get('peak_gpu_mb', 0):.2f} |",
        "",
        "---",
        "",
        "## 3. Inference Performance",
        "",
        "| Metric | Value |",
        "|--------|-------|",
        f"| Mean Latency (ms)   | {profiling_metrics.get('mean_ms', 0):.2f} ± {profiling_metrics.get('std_ms', 0):.2f} |",
        f"| Median Latency (ms) | {profiling_metrics.get('median_ms', 0):.2f} |",
        f"| Min Latency (ms)    | {profiling_metrics.get('min_ms', 0):.2f} |",
        f"| Max Latency (ms)    | {profiling_metrics.get('max_ms', 0):.2f} |",
        f"| FPS                 | {profiling_metrics.get('fps', 0):.1f} |",
        f"| CPU Utilisation     | {profiling_metrics.get('mean_cpu_pct', 0):.1f}% |",
        "",
        "---",
        "",
        "## 4. Energy Consumption",
        "",
        f"*Backend: {energy_metrics.get('backend', 'N/A')}*",
        "",
        "| Metric | Value |",
        "|--------|-------|",
        f"| Duration (s)             | {energy_metrics.get('duration_s', 0):.3f} |",
        f"| Mean Power (W)           | {energy_metrics.get('mean_power_w', 0):.4f} |",
        f"| Total Energy (J)         | {energy_metrics.get('energy_j', 0):.6f} |",
        f"| Energy / Inference (mJ)  | {energy_metrics.get('energy_mj_per_inference', 0):.6f} |",
        f"| CO₂ (kg) [if available]  | {energy_metrics.get('co2_kg', 'N/A')} |",
        "",
        "---",
        "",
        "## 5. Compression Ratio (Placeholder)",
        "",
        "| Model | Size (MB) | Compression |",
        "|-------|-----------|-------------|",
        f"| {label} (FP32) | {profiling_metrics.get('model_size_mb', 0):.2f} | 1.0× (baseline) |",
        "| PTQ INT8 | TBD | TBD |",
        "| QAT INT8 | TBD | TBD |",
        "",
        "---",
        "",
        "*Report generated by OCT wetAMD Segmentation Research Framework — Phase 2*",
    ]

    with open(path, "w") as f:
        f.write("\n".join(lines))

    _log.info(f"Markdown report saved → {path}")
    return path


# --------------------------------------------------------------------------- #
#  CSV export                                                                  #
# --------------------------------------------------------------------------- #

def save_full_results_csv(
    accuracy_metrics:  Dict[str, float],
    profiling_metrics: Dict[str, Any],
    energy_metrics:    Dict[str, Any],
    cfg,
    filename: str = "full_benchmark_results.csv",
) -> str:
    """
    Save all metrics to a single flat CSV row.

    Args:
        accuracy_metrics:  Segmentation metrics dict.
        profiling_metrics: Profiling metrics dict.
        energy_metrics:    Energy metrics dict.
        cfg:               Config.
        filename:          Output filename.

    Returns:
        Path to saved CSV.
    """
    combined = {
        "timestamp": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        **{f"acc_{k}":  v for k, v in accuracy_metrics.items()},
        **{f"prof_{k}": v for k, v in profiling_metrics.items()
           if k not in ("label", "device")},
        **{f"energy_{k}": v for k, v in energy_metrics.items()
           if k not in ("backend", "note")},
        "label":   profiling_metrics.get("label",  ""),
        "device":  profiling_metrics.get("device", ""),
        "backend": energy_metrics.get("backend",   ""),
    }

    path = os.path.join(cfg.csv_dir, filename)
    csv_log = CSVLogger(path, fieldnames=list(combined.keys()))
    csv_log.log(combined)

    _log.info(f"Full results CSV saved → {path}")
    return path


# --------------------------------------------------------------------------- #
#  Console summary table                                                       #
# --------------------------------------------------------------------------- #

def print_summary_table(
    accuracy_metrics:  Dict[str, float],
    profiling_metrics: Dict[str, Any],
    energy_metrics:    Dict[str, Any],
    label: str = "baseline_fp32",
) -> None:
    """Print a concise summary table to console."""
    print("\n" + "=" * 65)
    print(f"  BENCHMARK SUMMARY — {label}")
    print("=" * 65)
    print(f"  {'ACCURACY':}")
    print(f"    Mean Dice        : {accuracy_metrics.get('mean_dice', 0):.4f}")
    print(f"    Mean IoU         : {accuracy_metrics.get('mean_iou',  0):.4f}")
    print(f"    Pixel Accuracy   : {accuracy_metrics.get('pixel_acc', 0):.4f}")
    print(f"  {'COMPLEXITY':}")
    print(f"    Parameters       : {profiling_metrics.get('n_params', 0):,}")
    print(f"    Model size       : {profiling_metrics.get('model_size_mb', 0):.2f} MB")
    print(f"  {'PERFORMANCE':}")
    print(f"    FPS              : {profiling_metrics.get('fps', 0):.1f}")
    print(f"    Mean latency     : {profiling_metrics.get('mean_ms', 0):.2f} ms")
    print(f"    CPU utilisation  : {profiling_metrics.get('mean_cpu_pct', 0):.1f}%")
    print(f"  {'ENERGY':}")
    print(f"    Backend          : {energy_metrics.get('backend', 'N/A')}")
    print(f"    Energy / inf     : {energy_metrics.get('energy_mj_per_inference', 0):.4f} mJ")
    print(f"    Mean power       : {energy_metrics.get('mean_power_w', 0):.4f} W")
    print("=" * 65 + "\n")


# --------------------------------------------------------------------------- #
#  Comparison table (for future PTQ / QAT comparisons)                        #
# --------------------------------------------------------------------------- #

def print_comparison_table(results_list: List[Dict[str, Any]]) -> None:
    """
    Print a multi-model comparison table.

    Args:
        results_list: List of dicts, each containing:
                      label, mean_dice, fps, mean_ms, model_size_mb,
                      energy_mj_per_inference.
    """
    print("\n" + "=" * 90)
    print(f"  {'Label':<20} {'Dice':>8} {'FPS':>8} {'ms/inf':>8} "
          f"{'Size MB':>10} {'mJ/inf':>10}")
    print("-" * 90)
    for r in results_list:
        print(
            f"  {r.get('label',''):<20} "
            f"{r.get('mean_dice', 0):>8.4f} "
            f"{r.get('fps', 0):>8.1f} "
            f"{r.get('mean_ms', 0):>8.2f} "
            f"{r.get('model_size_mb', 0):>10.2f} "
            f"{r.get('energy_mj_per_inference', 0):>10.4f}"
        )
    print("=" * 90 + "\n")